param(
  [Parameter(Mandatory = $false)]
  [ValidateSet("Release", "Debug")]
  [string]$Config = "Release",

  [Parameter(Mandatory = $false)]
  [int]$Threads = 0,

  [Parameter(Mandatory = $false)]
  [ValidateSet("auto", "klu", "block")]
  [string]$Mode = "auto",

  [Parameter(Mandatory = $false)]
  [string]$FinalRoot = "",

  [Parameter(Mandatory = $true)]
  [string]$CandidateDll,

  [Parameter(Mandatory = $false)]
  [int]$TopK = 10,

  [Parameter(Mandatory = $false)]
  [string]$Tag = "profile_case12_13",

  # If set, skip running the test framework and only analyze an existing output directory
  # generated by this script (must contain run.log.txt and performance_report_*.csv).
  [Parameter(Mandatory = $false)]
  [string]$ReuseOutDir = ""
)

$ErrorActionPreference = "Stop"

function Resolve-RepoRoot { (Resolve-Path (Join-Path $PSScriptRoot "..\\..")).Path }

function Read-PerfCsv([string]$csvPath) {
  $rows = Import-Csv -Path $csvPath
  $out = @{}
  foreach ($r in $rows) {
    $id = [int](($r.TestCase) -replace "TestCase_", "")
    $out[$id] = [pscustomobject]@{
      id = $id
      prep_ms = [double]$r."PreparationTime(ms)"
      rearr_ms = [double]$r."RearrangementTime(ms)"
      decomp_ms = [double]$r."DecompositionTime(ms)"
      total_ms = [double]$r."TotalTime(ms)"
      nnz = if ($r.PSObject.Properties.Name -contains "NNZ") { [int64]$r.NNZ } else { 0 }
    }
  }
  return $out
}

function Parse-CaseSizesFromLog([string]$logPath) {
  $text = Get-Content -Path $logPath -Raw -Encoding Default
  $map = @{}
  $tableRx = [regex]'(?m)^TestCase_(\d+)\s+.*?\s+(\d+)\*(\d+)\s+'
  foreach ($m in $tableRx.Matches($text)) {
    $id = [int]$m.Groups[1].Value
    $n = [int]$m.Groups[2].Value
    $map[$id] = $n
  }
  return $map
}

function Parse-FinalSummaryTimes([string]$logPath, [int[]]$caseIds) {
  # Final summary table example (spaces vary):
  # TestCase_12 996.4  3461.1  44.5  4502.0  67869*67869  3486957  ...
  $lines = Get-Content -Path $logPath -Encoding Default
  $want = @{}
  foreach ($id in $caseIds) { $want["$id"] = $true }

  $out = @{}
  $rx = [regex]'(?m)^TestCase_(\d+)\s+([0-9]*\.?[0-9]+)\s+([0-9]*\.?[0-9]+)\s+([0-9]*\.?[0-9]+)\s+([0-9]*\.?[0-9]+)\s+(\d+)\*(\d+)\s+(\d+)\s+'
  foreach ($ln in $lines) {
    $m = $rx.Match($ln)
    if (-not $m.Success) { continue }
    $id = [int]$m.Groups[1].Value
    if (-not $want.ContainsKey("$id")) { continue }
    $out[$id] = [pscustomobject]@{
      id = $id
      rearr_ms = [double]$m.Groups[2].Value
      decomp_ms = [double]$m.Groups[3].Value
      solve_ms = [double]$m.Groups[4].Value
      total_ms = [double]$m.Groups[5].Value
      n = [int]$m.Groups[6].Value
      nnz = [int64]$m.Groups[8].Value
    }
  }
  return $out
}

function Segment-ProfileByCase([string]$logPath) {
  # Build segments keyed by n. Start a new segment whenever we see diag_stats for a new n.
  $lines = Get-Content -Path $logPath -Encoding Default
  $segments = @()
  $cur = $null

  $rxDiag = [regex]'USERALGO_PROFILE,diag_stats,n=(\d+),nnz=(\d+)'
  foreach ($ln in $lines) {
    $m = $rxDiag.Match($ln)
    if ($m.Success) {
      if ($cur) { $segments += $cur }
      $cur = [pscustomobject]@{
        n = [int]$m.Groups[1].Value
        nnz = [int64]$m.Groups[2].Value
        lines = New-Object System.Collections.Generic.List[string]
      }
      $null = $cur.lines.Add($ln)
      continue
    }
    if ($cur) { $null = $cur.lines.Add($ln) }
  }
  if ($cur) { $segments += $cur }
  return $segments
}

function Extract-TopK([string[]]$lines, [string]$tag) {
  # tag in {factor, solve}
  $rows = @()
  $rx = [regex]("USERALGO_PROFILE,block_topk_" + $tag + "_row,rank=(\\d+),bid=(-?\\d+),start=(-?\\d+),size=(-?\\d+),kernel=([^,]+),ms=([0-9eE\\.+-]+)")
  foreach ($ln in $lines) {
    $m = $rx.Match($ln)
    if (-not $m.Success) { continue }
    $rows += [pscustomobject]@{
      rank = [int]$m.Groups[1].Value
      bid = [int]$m.Groups[2].Value
      start = [int]$m.Groups[3].Value
      size = [int]$m.Groups[4].Value
      kernel = $m.Groups[5].Value
      ms = [double]$m.Groups[6].Value
    }
  }
  return @($rows | Sort-Object rank)
}

$repo = Resolve-RepoRoot
if (-not $FinalRoot) { $FinalRoot = Join-Path $repo "SparseMatrixLUTest_Final" }

if ($ReuseOutDir) {
  $outDir = (Resolve-Path $ReuseOutDir).Path
  $log = Join-Path $outDir "run.log.txt"
  $csvOut = Get-ChildItem -Path $outDir -Filter "performance_report_*.csv" -File -ErrorAction SilentlyContinue |
    Sort-Object LastWriteTime -Descending |
    Select-Object -First 1 |
    ForEach-Object { $_.FullName }
  if (-not (Test-Path $log)) { throw "Missing run.log.txt in ReuseOutDir: $outDir" }
  if (-not $csvOut) { throw "Missing performance_report_*.csv in ReuseOutDir: $outDir" }
  Write-Host ("ReuseOutDir: {0}" -f $outDir)
} else {
  $FinalRoot = (Resolve-Path $FinalRoot).Path

  $exe = Join-Path $FinalRoot ("x64\\{0}\\SparseMatrixLUTest.exe" -f $Config)
  $dllDir = Join-Path $FinalRoot ("x64\\{0}" -f $Config)
  $workDir = Join-Path $FinalRoot "SparseMatrixLUTest"
  if (-not (Test-Path $exe)) { throw "Missing exe: $exe" }
  if (-not (Test-Path $dllDir)) { throw "Missing dll dir: $dllDir" }
  if (-not (Test-Path $workDir)) { throw "Missing work dir: $workDir" }
  if (-not (Test-Path $CandidateDll)) { throw "Missing CandidateDll: $CandidateDll" }

  $ts = Get-Date -Format "yyyyMMdd_HHmmss"
  $outDir = Join-Path $repo ("build\\lutest_final_{0}_{1}_{2}" -f $ts, $Tag, $Mode)
  New-Item -ItemType Directory -Force -Path $outDir | Out-Null

  Write-Host ("OutDir:  {0}" -f $outDir)
  Write-Host ("Final:   {0}" -f $FinalRoot)
  Write-Host ("Config:  {0}  Mode: {1}  Threads: {2}  TopK: {3}" -f $Config, $Mode, $Threads, $TopK)

  # Place candidate DLL next to SparseMatrixLUTest.exe
  $dstDll = Join-Path $dllDir "useralgo_baseline.dll"
  Copy-Item -Force $CandidateDll $dstDll

  # Candidate env: profile on, refinement forced off, condition-refine off
  Remove-Item Env:USERALGO_MODE,Env:USERALGO_THREADS,Env:USERALGO_PROFILE,Env:USERALGO_REFINE_ITERS -ErrorAction SilentlyContinue
  Remove-Item Env:USERALGO_COND_REFINE,Env:USERALGO_COND_DIAG -ErrorAction SilentlyContinue
  Remove-Item Env:USERALGO_BLOCK_TOPK -ErrorAction SilentlyContinue
  $env:USERALGO_PROFILE = "1"
  $env:USERALGO_REFINE_ITERS = "0"
  $env:USERALGO_BLOCK_TOPK = "$TopK"
  if ($Mode) { $env:USERALGO_MODE = $Mode }
  if ($Threads -gt 0) { $env:USERALGO_THREADS = "$Threads" }

  # Prepare stdin: algorithm=1 (UserAlgorithm), draw=0
  $stdin = Join-Path $outDir "stdin.txt"
  ("1`r`n0`r`n") | Set-Content -NoNewline -Encoding ASCII $stdin

  $log = Join-Path $outDir "run.log.txt"
  $cmdFile = Join-Path $outDir "run.cmd"
  $start = Get-Date
  @(
    "@echo off"
    "setlocal"
    "set ""PATH=$dllDir;%PATH%"""
    "pushd ""$workDir"""
    """$exe"" < ""$stdin"" > ""$log"" 2>&1"
    "set ERR=%ERRORLEVEL%"
    "popd"
    "exit /b %ERR%"
  ) | Set-Content -Encoding Default $cmdFile

  $null = cmd.exe /d /c """$cmdFile"""

  $perfCsv = Get-ChildItem -Path $workDir -Filter "performance_report_*.csv" -File -ErrorAction SilentlyContinue |
    Where-Object { $_.LastWriteTime -gt $start.AddSeconds(-1) } |
    Sort-Object LastWriteTime -Descending |
    Select-Object -First 1
  if (-not $perfCsv) { throw "Missing performance_report_*.csv in $workDir" }

  $csvOut = Join-Path $outDir $perfCsv.Name
  Copy-Item -Force $perfCsv.FullName $csvOut

  # Optional cleanup of framework output file to keep the framework directory clean.
  try { Remove-Item -Force $perfCsv.FullName -ErrorAction SilentlyContinue } catch {}
}

$focus = @(12, 13)
$summary = Parse-FinalSummaryTimes $log $focus
if (-not $summary -or $summary.Count -lt 2) { throw "Failed to parse final summary table for case12/13 from: $log" }

$rows = @()
foreach ($id in $focus) {
  $s = $summary[$id]
  $n = [int]$s.n
  $total = [double]$s.total_ms
  $rearr = [double]$s.rearr_ms
  $decomp = [double]$s.decomp_ms
  $solve = [double]$s.solve_ms
  $rows += [pscustomobject]@{
    TestCase = "TestCase_$id"
    N = $n
    NNZ = [int64]$s.nnz
    TotalMs = $total
    RearrMs = $rearr
    DecompMs = $decomp
    SolveMs = $solve
    RearrPct = if ($total -eq 0) { [double]::NaN } else { 100.0 * $rearr / $total }
    DecompPct = if ($total -eq 0) { [double]::NaN } else { 100.0 * $decomp / $total }
    SolvePct = if ($total -eq 0) { [double]::NaN } else { 100.0 * $solve / $total }
  }
}

$breakCsv = Join-Path $outDir "case12_13_breakdown.csv"
$rows | Export-Csv -NoTypeInformation -Encoding UTF8 $breakCsv

$md = Join-Path $outDir "case12_13_breakdown.md"
$lines = @()
$lines += "# Case12/13 Breakdown (Profile Run)"
$lines += ""
$lines += "- Mode: $Mode"
$lines += "- Threads: $Threads"
$lines += "- USERALGO_PROFILE=1, USERALGO_REFINE_ITERS=0, USERALGO_COND_REFINE=0"
$lines += "- Perf CSV: $(Split-Path $csvOut -Leaf)"
$lines += ""
$lines += "## Rearr/Decomp/Solve breakdown"
$lines += ""
$lines += "| TestCase | N | NNZ | TotalMs | RearrMs | DecompMs | SolveMs | Rearr% | Decomp% | Solve% |"
$lines += "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"
foreach ($r in $rows) {
  $lines += ("| {0} | {1} | {2} | {3:N3} | {4:N3} | {5:N3} | {6:N3} | {7:N2} | {8:N2} | {9:N2} |" -f $r.TestCase, $r.N, $r.NNZ, $r.TotalMs, $r.RearrMs, $r.DecompMs, $r.SolveMs, $r.RearrPct, $r.DecompPct, $r.SolvePct)
}
$lines += ""

$segments = Segment-ProfileByCase $log
foreach ($id in $focus) {
  $n = [int]$summary[$id].n
  $seg = $segments | Where-Object { $_.n -eq $n } | Select-Object -First 1
  # Ensure we pass a plain string[] to downstream parsers.
  $plines = if ($seg) { @($seg.lines) } else { @() }
  # Inline parse (more robust than relying on function output semantics).
  $factorTop = @()
  $solveTop = @()
  $rxFactor = [regex]'USERALGO_PROFILE,block_topk_factor_row,rank=(\d+),bid=(-?\d+),start=(-?\d+),size=(-?\d+),kernel=([^,]+),ms=([0-9eE\.+-]+)'
  $rxSolve = [regex]'USERALGO_PROFILE,block_topk_solve_row,rank=(\d+),bid=(-?\d+),start=(-?\d+),size=(-?\d+),kernel=([^,]+),ms=([0-9eE\.+-]+)'
  foreach ($ln in $plines) {
    $m = $rxFactor.Match($ln)
    if ($m.Success) {
      $factorTop += [pscustomobject]@{
        rank = [int]$m.Groups[1].Value
        bid = [int]$m.Groups[2].Value
        start = [int]$m.Groups[3].Value
        size = [int]$m.Groups[4].Value
        kernel = $m.Groups[5].Value
        ms = [double]$m.Groups[6].Value
      }
      continue
    }
    $m = $rxSolve.Match($ln)
    if ($m.Success) {
      $solveTop += [pscustomobject]@{
        rank = [int]$m.Groups[1].Value
        bid = [int]$m.Groups[2].Value
        start = [int]$m.Groups[3].Value
        size = [int]$m.Groups[4].Value
        kernel = $m.Groups[5].Value
        ms = [double]$m.Groups[6].Value
      }
    }
  }
  $factorTop = @($factorTop | Sort-Object rank)
  $solveTop = @($solveTop | Sort-Object rank)

  $lines += ("## TestCase_{0} profile snippets (n={1})" -f $id, $n)
  $lines += ""

  $lines += "### Key profile lines"
  $lines += ""
  foreach ($pat in @("mode_select", "thread_select", "klu_analyze_ms", "klu_factor_ms", "btf_build_ms", "block_build_ms", "factor_blocks")) {
    $hit = $plines | Where-Object { $_ -like ("USERALGO_PROFILE," + $pat + "*") }
    foreach ($h in $hit) { $lines += "- $h" }
  }
  if (($plines | Where-Object { $_ -like "USERALGO_PROFILE,*" }).Count -eq 0) {
    $lines += "- (no USERALGO_PROFILE lines captured for this case)"
  }
  $lines += ""

  if (@($factorTop).Count -gt 0) {
    $lines += "### block_topk_factor_row"
    $lines += ""
    $lines += "| rank | bid | start | size | kernel | ms |"
    $lines += "|---:|---:|---:|---:|---:|---:|"
    foreach ($t in (@($factorTop) | Select-Object -First $TopK)) {
      $lines += ("| {0} | {1} | {2} | {3} | {4} | {5:N3} |" -f $t.rank, $t.bid, $t.start, $t.size, $t.kernel, $t.ms)
    }
    $lines += ""
  } else {
    $lines += "- (no block_topk_factor_row found; this case likely ran global KLU path)"
    $lines += ""
  }

  if (@($solveTop).Count -gt 0) {
    $lines += "### block_topk_solve_row"
    $lines += ""
    $lines += "| rank | bid | start | size | kernel | ms |"
    $lines += "|---:|---:|---:|---:|---:|---:|"
    foreach ($t in (@($solveTop) | Select-Object -First $TopK)) {
      $lines += ("| {0} | {1} | {2} | {3} | {4} | {5:N3} |" -f $t.rank, $t.bid, $t.start, $t.size, $t.kernel, $t.ms)
    }
    $lines += ""
  } else {
    $lines += "- (no block_topk_solve_row found; this case likely ran global KLU path or reverse solve without profiling)"
    $lines += ""
  }
}

$lines | Set-Content -Encoding UTF8 $md

Write-Host ("Log:       {0}" -f $log)
Write-Host ("Perf CSV:  {0}" -f $csvOut)
Write-Host ("Breakdown: {0}" -f $breakCsv)
Write-Host ("MD:        {0}" -f $md)

[pscustomobject]@{
  out_dir = $outDir
  log = $log
  perf_csv = $csvOut
  breakdown_csv = $breakCsv
  breakdown_md = $md
}
